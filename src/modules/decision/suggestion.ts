import type {
    ClassifierAnswer,
    ClassifierApi,
    ClassifierContext,
    ClassifierModel,
    ClassifierQuestion,
    ClassifierResult,
    JsonObject,
    Usage,
} from "@earendil-works/pi-ai";

import { resolveClassifier, type ClassifierRegistry } from "./model";
import type { DecisionModelConfig } from "./types";

/**
 * The session-rule suggestion subject: one question about the arguments of a command whose rule the prompt
 * may remember.
 *
 * This is not a permission question and it never grants anything. It exists because the suggestion table
 * cannot tell whether a path-like argument is data (`vitest test/a.test.ts`) or the program that runs
 * (`tsx script.ts`) when the package runner is unrecognized, so it errs toward pinning the path. The answer
 * here only chooses between two patterns the table already built — `code` keeps the narrow one, `data` lets
 * the caller use the wider one — and the pattern itself is never generated by the model. Measured on a
 * 30-command battery, this yes/no reached 29/30 while asking the model to choose a pattern directly picked a
 * wildcard around executed code (`npx tsx *`, `npx tsx -e *`) twice.
 *
 * The state also carries the commands from this session that name the same tool, because an unrecognized
 * tool's argument role is only inferable from what the session has already done with it: with one previous
 * `npx zorch run test/bar.test.ts` the same question moved from 0.80 (code) to 0.36 (data). The window is
 * filtered rather than a general transcript — a mixed recent window left the answer at 0.61.
 */

/** The question id in the request and the answer map. */
export const SUGGESTION_QUESTION_ID = "executes_code";

/**
 * The measured wording. Answering "no" is the direction that widens a rule, so the instruction names the
 * data shapes explicitly instead of relying on a bare "does it execute code".
 */
export const SUGGESTION_INSTRUCTION =
    "Does this command execute code whose contents come from one of its arguments (a script file or an " +
    "inline snippet)? Answer no when arguments are paths, filters, flags, names, or selectors the tool " +
    "operates on.";

export const SUGGESTION_CRITERIA = {
    true: "an argument's contents are executed as code, for example a script file or an inline snippet",
    false: "arguments are data: paths, filters, selectors, names, or flags the tool operates on",
} as const;

const ROLE_QUESTION: ClassifierQuestion = {
    type: "bool",
    instructions: SUGGESTION_INSTRUCTION,
    criteria: { ...SUGGESTION_CRITERIA },
};

/** What the invocation's arguments are: a program it runs, or data it operates on. */
export type SuggestionRole = "code" | "data";

/** The probability below which the answer is read as `data`. */
export const SUGGESTION_DATA_THRESHOLD = 0.5;

export interface SuggestionContext {
    /** The single uncovered segment, as text; not the whole command line. */
    command: string;
    cwd: string;
    /** Commands from this session that name the same tool, oldest first. */
    recentCommands?: readonly string[];
}

/** The classifier state: the segment, and the same-tool commands that precede it. */
export function buildSuggestionState(context: SuggestionContext): JsonObject {
    const state: JsonObject = { command: context.command, cwd: context.cwd };

    if (context.recentCommands !== undefined && context.recentCommands.length > 0) {
        state.recent_commands = [...context.recentCommands];
    }

    return state;
}

/** One request, one question. */
export function suggestionRequest(state: JsonObject): ClassifierContext {
    return { state, questions: { [SUGGESTION_QUESTION_ID]: ROLE_QUESTION } };
}

/**
 * Read the role answer, or `undefined` when the reply names no readable role.
 *
 * The probability is read against a threshold, not a confidence floor: this is a label that picks between two
 * patterns, and the caller still shows the chosen pattern to the person. An unreadable reply abstains, so the
 * table's own suggestion stays in place.
 */
export function suggestionRoleFrom(
    answers: Record<string, ClassifierAnswer>,
): SuggestionRole | undefined {
    const answer = answers[SUGGESTION_QUESTION_ID];
    if (answer === undefined || answer.type !== "bool") {
        return undefined;
    }

    return answer.probability >= SUGGESTION_DATA_THRESHOLD ? "code" : "data";
}

/** How one suggestion consult ended, for tests and the caller. */
export type SuggestionStatus =
    "answered" | "cached" | "cooldown" | "abstained" | "error" | "timeout" | "disabled";

export interface SuggestionConsult {
    /** Present when the model named a role. */
    role?: SuggestionRole;
    status: SuggestionStatus;
    latencyMs: number;
    usage?: Usage;
}

const DEFAULT_TIMEOUT_MS = 5000;
const DEFAULT_COOLDOWN_MS = 30000;
const CACHE_LIMIT = 64;

export interface SuggestionEvaluatorOptions {
    registry: ClassifierRegistry;
    config: DecisionModelConfig;
    /** Clock, injectable so cooldown tests can advance time without sleeping. */
    now?: () => number;
}

type Classifier = ClassifierModel<ClassifierApi>;

/**
 * One consult of the role question, with its own cache and cooldown.
 *
 * Deliberately separate from `DecisionEvaluator`: that evaluator's cooldown, cache, and folds are about
 * authority, and a suggestion grants none. Keeping them apart means a failed suggestion request cannot pause
 * a permission verdict, and adding the question to the veto request cannot perturb the wording measurements
 * the veto ships on. The process-wide instance is keyed by config in `gate.ts`.
 */
export class SuggestionEvaluator {
    private readonly now: () => number;
    private readonly cache = new Map<string, SuggestionRole>();
    private cooldownUntil = 0;

    constructor(private readonly options: SuggestionEvaluatorOptions) {
        this.now = options.now ?? Date.now;
    }

    async evaluate(context: SuggestionContext): Promise<SuggestionConsult> {
        const { config } = this.options;
        if (config.enabled !== true || config.suggestions === false) {
            return { status: "disabled", latencyMs: 0 };
        }

        const model = resolveClassifier(this.options.registry, config);
        if (model === undefined) {
            return { status: "disabled", latencyMs: 0 };
        }

        const key = suggestionCacheKey(model, context);
        const cached = this.cache.get(key);
        if (cached !== undefined) {
            return { role: cached, status: "cached", latencyMs: 0 };
        }

        if (this.now() < this.cooldownUntil) {
            return { status: "cooldown", latencyMs: 0 };
        }

        const started = this.now();
        const classified = await this.classify(
            model,
            suggestionRequest(buildSuggestionState(context)),
        );
        const { result } = classified;
        const latencyMs = this.now() - started;

        if (result.stopReason !== "stop") {
            this.cooldownUntil = this.now() + (config.cooldownMs ?? DEFAULT_COOLDOWN_MS);
            const status = classified.timedOut ? "timeout" : "error";

            return {
                status,
                latencyMs,
                ...(result.usage === undefined ? {} : { usage: result.usage }),
            };
        }

        const role = suggestionRoleFrom(result.answers);
        if (role === undefined) {
            return {
                status: "abstained",
                latencyMs,
                ...(result.usage === undefined ? {} : { usage: result.usage }),
            };
        }

        this.remember(key, role);

        return {
            role,
            status: "answered",
            latencyMs,
            ...(result.usage === undefined ? {} : { usage: result.usage }),
        };
    }

    private remember(key: string, role: SuggestionRole): void {
        if (this.cache.size >= CACHE_LIMIT) {
            const oldest = this.cache.keys().next().value;
            if (oldest !== undefined) {
                this.cache.delete(oldest);
            }
        }

        this.cache.set(key, role);
    }

    private async classify(
        model: Classifier,
        context: ClassifierContext,
    ): Promise<{ result: ClassifierResult; timedOut: boolean }> {
        const timeoutMs = this.options.config.timeoutMs ?? DEFAULT_TIMEOUT_MS;
        const controller = new AbortController();
        const timer = setTimeout(() => controller.abort(), timeoutMs);

        try {
            const result = await this.options.registry.classify(model, context, {
                signal: controller.signal,
            });

            return { result, timedOut: controller.signal.aborted };
        } catch (error) {
            return {
                result: errorResult(model, messageOf(error)),
                timedOut: controller.signal.aborted,
            };
        } finally {
            clearTimeout(timer);
        }
    }
}

/**
 * A suggestion answer keyed by everything that can change it: the model, the segment, and the same-tool
 * commands the state carries. The recent window is in the key on purpose, unlike the veto's command cache:
 * the answer for an unrecognized tool flips when the session's own history changes, and serving the earlier
 * answer would ignore exactly the evidence this subject exists to use.
 */
function suggestionCacheKey(model: Classifier, context: SuggestionContext): string {
    return JSON.stringify([
        model.provider,
        model.id,
        context.command,
        context.recentCommands ?? [],
    ]);
}

function messageOf(error: unknown): string {
    return error instanceof Error ? error.message : String(error);
}

/** The error result shape, so a thrown classify is treated exactly like a provider failure. */
function errorResult(model: Classifier, errorMessage: string): ClassifierResult {
    return {
        api: model.api,
        provider: model.provider,
        model: model.id,
        answers: {},
        stopReason: "error",
        errorMessage,
        timestamp: 0,
    };
}
